<?php

namespace App\Http\Controllers;

use App\Models\Menu;
use App\Models\Kategori;
use Illuminate\Http\Request;

class MenuController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | HALAMAN MENU
    |--------------------------------------------------------------------------
    */

    public function index(Request $request)
    {
        /*
        |--------------------------------------------------------------------------
        | Ambil semua kategori
        |--------------------------------------------------------------------------
        */

        $kategoris = Kategori::orderBy('kategori_id')->get();


        /*
        |--------------------------------------------------------------------------
        | Query menu
        |--------------------------------------------------------------------------
        */

        $query = Menu::with('kategori');


        /*
        |--------------------------------------------------------------------------
        | FILTER KATEGORI
        |--------------------------------------------------------------------------
        */

        if ($request->filled('kategori')) {

            $query->where(
                'kategori_id',
                $request->kategori
            );
        }


        /*
        |--------------------------------------------------------------------------
        | SEARCH
        |--------------------------------------------------------------------------
        */

        if ($request->filled('search')) {

            $search = $request->search;

            $query->where(
                'nama_menu',
                'like',
                '%' . $search . '%'
            );
        }


        /*
        |--------------------------------------------------------------------------
        | Ambil menu
        |--------------------------------------------------------------------------
        */

        $menus = $query
            ->orderBy('menu_id')
            ->get();


        /*
        |--------------------------------------------------------------------------
        | Kirim ke halaman menu
        |--------------------------------------------------------------------------
        */

        return view(
            'menu',
            compact(
                'menus',
                'kategoris'
            )
        );
    }



    /*
    |--------------------------------------------------------------------------
    | DETAIL MENU
    |--------------------------------------------------------------------------
    */

    public function show($id)
    {
        /*
        |--------------------------------------------------------------------------
        | Cari menu berdasarkan menu_id
        |--------------------------------------------------------------------------
        */

        $menu = Menu::with('kategori')
            ->where('menu_id', $id)
            ->firstOrFail();


        /*
        |--------------------------------------------------------------------------
        | Ambil rekomendasi dari kategori yang sama
        |--------------------------------------------------------------------------
        */

        $rekomendasi = Menu::with('kategori')
            ->where('kategori_id', $menu->kategori_id)
            ->where('menu_id', '!=', $menu->menu_id)
            ->where('stok', '>', 0)
            ->orderBy('menu_id')
            ->limit(3)
            ->get();


        /*
        |--------------------------------------------------------------------------
        | Tampilkan detail
        |--------------------------------------------------------------------------
        */

        return view(
            'menu-detail',
            compact(
                'menu',
                'rekomendasi'
            )
        );
    }
}